import Foundation
import PhotoAgainCore

public enum HintCategory: String, Codable, Sendable { case focus, exposure, framing, occlusion }
public enum HintRegion: String, Codable, Sendable {
  case wholeFrame, upperLeft, upperRight, center, lowerLeft, lowerRight
}
public struct VisibleHint: Codable, Sendable, Equatable {
  public let memberIDs: [String]
  public let category: HintCategory
  public let region: HintRegion
}
/// Fixed vocabulary: requests a human check, never a score or a preferred photo.
public struct GroupHints: Codable, Sendable {
  public let schemaVersion: Int
  public let datasetID: String
  public let memberIDs: [String]
  public let abstained: Bool
  public let hints: [VisibleHint]
  public func validate(datasetID: String, memberIDs: [String]) throws {
    guard schemaVersion == 1, UUID(uuidString: datasetID) != nil, self.datasetID == datasetID,
      (2...4).contains(memberIDs.count), Set(memberIDs).count == memberIDs.count,
      self.memberIDs == memberIDs, hints.count <= 8,
      abstained ? hints.isEmpty : !hints.isEmpty
    else { throw OllamaError.invalidHints }
    for hint in hints {
      guard !hint.memberIDs.isEmpty, hint.memberIDs.count <= memberIDs.count,
        Set(hint.memberIDs).count == hint.memberIDs.count,
        Set(hint.memberIDs).isSubset(of: Set(memberIDs))
      else { throw OllamaError.invalidHints }
    }
    guard
      Set(hints.map { "\($0.memberIDs.sorted())|\($0.category)|\($0.region)" }).count == hints.count
    else { throw OllamaError.invalidHints }
  }
  public static func decode(_ data: Data, datasetID: String, memberIDs: [String]) throws -> Self {
    guard data.count <= 32_768,
      let object = try JSONSerialization.jsonObject(with: data) as? [String: Any],
      Set(object.keys) == ["schemaVersion", "datasetID", "memberIDs", "abstained", "hints"],
      let hints = object["hints"] as? [[String: Any]],
      hints.allSatisfy({ Set($0.keys) == ["memberIDs", "category", "region"] })
    else { throw OllamaError.invalidHints }
    let value = try JSONDecoder().decode(Self.self, from: data)
    try value.validate(datasetID: datasetID, memberIDs: memberIDs)
    return value
  }
}

public enum OllamaError: String, Error, Sendable {
  case acknowledgementRequired, invalidRequest, invalidHints, invalidMetadata
  case unavailableModel, missingVision, unsafeEndpoint, responseTooLarge, invalidResponse
}

/// Provenance is generated by the adapter, never accepted from model text.
public struct GroupHintsDocument: Codable, Sendable {
  public let schemaVersion: Int
  public let capability: String
  public let requestID: String
  public let provider: String
  public let adapterVersion: String
  public let runtimeTrust: String
  public let model: String
  public let modelDigest: String
  public let comparison: GroupHints
}
